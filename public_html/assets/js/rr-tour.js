    function positionCentered(pop) {
        var box = visibleBox();
        pop.style.right = '';
        pop.style.bottom = '';
        pop.style.width = '';
        pop.style.left = (box.left + box.width / 2) + 'px';
        pop.style.top = (box.top + box.height / 2) + 'px';
        pop.style.maxWidth = Math.max(0, box.width - 24) + 'px';
        pop.style.maxHeight = Math.max(0, box.height - 24) + 'px';
    }

