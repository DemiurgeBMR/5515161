-- Раньше "запрос на закрепление" был отдельной заявкой (новая строка в
-- applications с initial_message='Запрос на закрепление'), создаваемой
-- сразу с карточки локации — то есть оператор мог начать общение с
-- владельцем сразу с "закрепи меня", в обход обычного чата.
--
-- Теперь закрепление — это действие НАД уже существующей заявкой/чатом:
-- оператор сначала просто пишет владельцу (обычная заявка), а запрос на
-- закрепление отправляет отдельной кнопкой прямо внутри чата, когда сам
-- решит. Это устраняет необходимость создавать вторую параллельную заявку
-- на ту же локацию — вся история остаётся в одном чате.

ALTER TABLE `applications`
    ADD COLUMN `assignment_requested` tinyint(1) NOT NULL DEFAULT 0 AFTER `operator_approved`;
