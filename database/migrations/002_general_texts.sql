-- Описания номеров без медицинской темы. Меняются только тексты,
-- которые остались от первой версии: если вы уже переписали описание
-- в админке, оно не тронется.

UPDATE room_types SET summary = 'На одного или двоих. Всё нужное, чтобы хорошо выспаться и отдохнуть после дороги.'
WHERE summary = 'На одного или двоих. Всё нужное для спокойного отдыха между процедурами.';

UPDATE room_types SET summary = 'Для семьи, коллег в командировке или двух гостей, которым нужно больше места.'
WHERE summary = 'Для семьи или двух гостей, которым нужно больше места: например, пациент и сопровождающий.';
