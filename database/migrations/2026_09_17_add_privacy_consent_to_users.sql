-- Согласие на обработку персональных данных — с 1 сентября 2025 обязано быть
-- отдельным действием пользователя, а не пунктом внутри общего пользовательского
-- соглашения, и оператор должен уметь подтвердить сам факт согласия (ст. 9
-- 152-ФЗ). Храним не только факт (иначе не отличить пользователя, реально
-- поставившего галочку, от зарегистрированного до её появления), а и когда
-- именно оно было дано — если политика конфиденциальности потом изменится,
-- эта дата покажет, по какой именно редакции пользователь давал согласие.
--
-- NULL для всех, кто уже зарегистрирован до этой миграции: согласие,
-- полученное задним числом, юридической силы не имеет — эти аккаунты
-- остаются как есть, требование действует только для новых регистраций.
ALTER TABLE `users`
    ADD COLUMN `privacy_consent_at` timestamp NULL DEFAULT NULL AFTER `is_verified`;
